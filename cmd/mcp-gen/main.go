// gen regenerates internal/mcptools/tools_gen.go from the OpenAPI spec. Run
// via the Makefile (make mcp-tools) — never edit the output by hand. The
// table serves the remote MCP endpoint (/mcp).
//
// Usage: go run ./cmd/mcp-gen <path-to-openapi.yaml> <output.go>
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"log"
	"maps"
	"os"
	"slices"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
	"github.com/naufal/latasya-erp/internal/mcptools"
)

// excludedReasons documents why an operation is not an MCP tool. The coverage
// test asserts this list matches the generated output.
var excludedReasons = map[string]string{
	"login":            "cookie-session semantics; passwords never enter LLM context",
	"logout":           "cookie-session semantics",
	"getCSRFToken":     "CSRF is cookie-path-only",
	"getOpenAPISpec":   "public meta, no ERP data",
	"listCapabilities": "public meta, no ERP data",
	"createAPIToken":   "server rejects bearer callers; a token must never spawn a token",
	"revokeAPIToken":   "server rejects bearer callers",
}

const wireNotes = `Wire formats: amounts are integer IDR strings ("50000"); quantities decimal strings with up to 2 places ("1.50"); dates "YYYY-MM-DD"; timestamps ISO-8601 UTC; lists return {"data":[...],"meta":{"page",...}}.`

func main() {
	if len(os.Args) != 3 {
		log.Fatalf("usage: %s <openapi.yaml> <output.go>", os.Args[0])
	}
	loader := openapi3.NewLoader()
	doc, err := loader.LoadFromFile(os.Args[1])
	if err != nil {
		log.Fatalf("load spec: %v", err)
	}

	// Tool paths are emitted fully qualified with the spec's server base
	// path ("/api/v1") so the dispatcher needs no prefix knowledge.
	apiPrefix := ""
	if len(doc.Servers) > 0 && doc.Servers[0].URL != "" && doc.Servers[0].URL != "/" {
		apiPrefix = strings.TrimSuffix(doc.Servers[0].URL, "/")
	}

	var defs []mcptools.ToolDef
	for path, item := range doc.Paths.Map() {
		for method, op := range item.Operations() {
			if op == nil {
				continue
			}
			name := op.OperationID
			if _, excluded := excludedReasons[name]; excluded {
				assertClassified(name, op)
				continue
			}
			if auth := extString(op.Extensions, "x-latasya-auth"); auth == "cookie-only" || auth == "public" {
				log.Fatalf("%s is %s in the spec but missing from gen's exclusion list — classify it", name, auth)
			}
			defs = append(defs, buildTool(doc, method, apiPrefix+path, op))
		}
	}
	sort.Slice(defs, func(i, j int) bool { return defs[i].Name < defs[j].Name })

	// The tool table is emitted as JSON, not Go composite literals, and
	// decoded at init by the mcptools package: immune to Go syntax drift and
	// still one blob for review.
	encoded, err := json.Marshal(defs)
	if err != nil {
		log.Fatalf("encode tools: %v", err)
	}

	var b strings.Builder
	b.WriteString("// Code generated by gen from api/openapi.yaml; DO NOT EDIT.\n\npackage mcptools\n\n")
	b.WriteString("// ExcludedOperations are spec operations deliberately not exposed as tools.\nvar ExcludedOperations = map[string]string{\n")
	for _, name := range slices.Sorted(maps.Keys(excludedReasons)) {
		fmt.Fprintf(&b, "\t%q: %q,\n", name, excludedReasons[name])
	}
	b.WriteString("}\n\n")
	b.WriteString("const toolsJSON = `")
	b.Write(encoded)
	b.WriteString("`\n\n")
	b.WriteString("// GeneratedTools holds one ToolDef per exposed operation.\nvar GeneratedTools = mustDecodeTools(toolsJSON)\n")

	if err := os.WriteFile(os.Args[2], []byte(b.String()), 0o644); err != nil {
		log.Fatalf("write output: %v", err)
	}
	fmt.Printf("generated %d tools, excluded %d operations\n", len(defs), len(excludedReasons))
}

// assertClassified keeps the exclusion list honest: every excluded operation
// must carry a matching x-latasya-auth class in the spec.
func assertClassified(name string, op *openapi3.Operation) {
	auth := extString(op.Extensions, "x-latasya-auth")
	if name == "logout" {
		return // cookie-session by nature
	}
	if auth != "cookie-only" && auth != "public" {
		log.Fatalf("%s is excluded but its x-latasya-auth is %q (want cookie-only/public)", name, auth)
	}
}

func buildTool(doc *openapi3.T, method, path string, op *openapi3.Operation) mcptools.ToolDef {
	var t mcptools.ToolDef
	t.Name = op.OperationID
	t.Method = method
	t.PathTmpl = path
	t.Capability = extString(op.Extensions, "x-latasya-capability")

	summary := op.Summary
	if summary == "" {
		summary = t.Name
	}
	t.Description = summary + ". " + wireNotes

	// Annotations per HTTP method; destructive POSTs are named for it.
	t.Annotations = mcptools.ToolAnnotations{ReadOnly: true, Idempotent: true}
	if method != "GET" {
		t.Mutation = true
		t.Annotations = mcptools.ToolAnnotations{}
		if method == "DELETE" ||
			strings.Contains(strings.ToLower(op.OperationID), "delete") ||
			strings.Contains(strings.ToLower(op.OperationID), "void") {
			t.Annotations.Destructive = true
			t.Annotations.Idempotent = true
		}
	}

	for _, p := range op.Parameters {
		if p.Value == nil {
			continue
		}
		in := p.Value.In
		if in != "path" && in != "query" {
			continue // header params (Idempotency-Key) are never exposed
		}
		typ := "string"
		if s := p.Value.Schema.Value; s != nil && s.Type != nil {
			switch {
			case s.Type.Permits(openapi3.TypeInteger):
				typ = "integer"
			case s.Type.Permits(openapi3.TypeNumber):
				typ = "number"
			case s.Type.Permits(openapi3.TypeBoolean):
				typ = "boolean"
			}
		}
		t.Params = append(t.Params, mcptools.ParamDef{
			Name: p.Value.Name, In: in, Type: typ, Required: p.Value.Required,
		})
	}

	if op.RequestBody != nil && op.RequestBody.Value != nil {
		for _, media := range op.RequestBody.Value.Content {
			if media.Schema == nil || media.Schema.Value == nil {
				continue
			}
			// $refs are resolved before emission: an MCP client cannot
			// resolve "#/components/schemas/..." pointers. Mutating the
			// shared doc is fine — the generator process exits after.
			if raw, err := resolveRefs(doc, media.Schema, 0).MarshalJSON(); err == nil {
				t.BodySchema = compactJSON(raw)
			}
			break
		}
	}

	// PDF responses become resource content blocks.
	if op.Responses != nil {
		if r, ok := op.Responses.Map()["200"]; ok && r.Value != nil {
			if _, isPDF := r.Value.Content["application/pdf"]; isPDF {
				t.IsPDF = true
				t.Annotations = mcptools.ToolAnnotations{ReadOnly: true, Idempotent: true}
				t.Mutation = false
			}
		}
	}
	return t
}

// resolveRefs inlines "#/components/schemas/..." pointers so the emitted
// body schemas are self-contained. Depth-capped against pathological specs.
func resolveRefs(doc *openapi3.T, ref *openapi3.SchemaRef, depth int) *openapi3.SchemaRef {
	if ref == nil || depth > 8 {
		return ref
	}
	if ref.Ref != "" {
		name := strings.TrimPrefix(ref.Ref, "#/components/schemas/")
		if target, ok := doc.Components.Schemas[name]; ok && target.Value != nil {
			return resolveRefs(doc, target, depth+1)
		}
	}
	if ref.Value != nil {
		for k, p := range ref.Value.Properties {
			ref.Value.Properties[k] = resolveRefs(doc, p, depth+1)
		}
		if ref.Value.Items != nil {
			ref.Value.Items = resolveRefs(doc, ref.Value.Items, depth+1)
		}
	}
	return ref
}

func compactJSON(raw []byte) []byte {
	var buf bytes.Buffer
	if err := json.Compact(&buf, raw); err != nil {
		return raw
	}
	return buf.Bytes()
}

func extString(ext map[string]any, key string) string {
	v, ok := ext[key]
	if !ok {
		return ""
	}
	switch val := v.(type) {
	case string:
		return val
	case json.RawMessage:
		var s string
		if json.Unmarshal(val, &s) == nil {
			return s
		}
	}
	return ""
}
