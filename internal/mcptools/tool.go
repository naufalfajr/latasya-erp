// Package mcptools holds the MCP tool bindings generated from the OpenAPI
// spec (tools_gen.go, emitted by cmd/mcp-server/gen) plus the schema helpers
// the client uses to serve them.
package mcptools

import "encoding/json"

// ToolAnnotations mirrors the MCP 2025-06-18 tool annotation hints.
type ToolAnnotations struct {
	ReadOnly    bool `json:"readOnlyHint"`
	Destructive bool `json:"destructiveHint"`
	Idempotent  bool `json:"idempotentHint"`
}

// ParamDef is one path or query parameter of an operation.
type ParamDef struct {
	Name     string `json:"name"`
	In       string `json:"in"` // "path" | "query"
	Type     string `json:"type"`
	Required bool   `json:"required"`
}

// ToolDef is one generated MCP tool: a 1:1 binding to an OpenAPI operation.
// Generated by cmd/mcp-server/gen from api/openapi.yaml; never hand-edited.
type ToolDef struct {
	Name        string          `json:"name"`        // the operationId, verbatim
	Method      string          `json:"method"`      // GET | POST | PUT | DELETE
	PathTmpl    string          `json:"path"`        // "/api/v1/invoices/{id}"
	Description string          `json:"description"` // summary + wire-format notes
	Capability  string          `json:"capability"`  // "" = any authenticated user
	Annotations ToolAnnotations `json:"annotations"`
	Mutation    bool            `json:"mutation"` // auto idempotency key
	IsPDF       bool            `json:"is_pdf"`
	Params      []ParamDef      `json:"params,omitempty"`
	// BodySchema is the JSON Schema (object) of the request body, verbatim
	// from the spec, or nil for operations without one.
	BodySchema json.RawMessage `json:"body_schema,omitempty"`
}

// ListEntry is the tool descriptor sent in tools/list.
type ListEntry struct {
	Name        string          `json:"name"`
	Description string          `json:"description"`
	InputSchema json.RawMessage `json:"inputSchema"`
	Annotations ToolAnnotations `json:"annotations,omitempty"`
}

// InputSchema merges path params, query params, and the body into one flat
// JSON Schema object for the model to fill. The Idempotency-Key header is
// never exposed: the dispatcher derives it.
func (t ToolDef) InputSchema() json.RawMessage {
	props := map[string]any{}
	var required []string
	for _, p := range t.Params {
		props[p.Name] = map[string]any{"type": p.Type}
		if p.Required {
			required = append(required, p.Name)
		}
	}
	if len(t.BodySchema) > 0 {
		props["body"] = t.BodySchema
	}
	if t.Mutation {
		props["_idempotency_key"] = map[string]any{
			"type":        "string",
			"description": "Optional. Pass the SAME value across retries to replay instead of duplicating.",
		}
	}
	schema := map[string]any{
		"type":       "object",
		"properties": props,
	}
	if len(required) > 0 {
		schema["required"] = required
	}
	out, err := json.Marshal(schema)
	if err != nil {
		return json.RawMessage(`{"type":"object"}`)
	}
	return out
}

// ToListEntry renders the descriptor for tools/list.
func (t ToolDef) ToListEntry() ListEntry {
	return ListEntry{
		Name:        t.Name,
		Description: t.Description,
		InputSchema: t.InputSchema(),
		Annotations: t.Annotations,
	}
}

// Find returns the tool with the given name.
func Find(name string) *ToolDef {
	for i := range GeneratedTools {
		if GeneratedTools[i].Name == name {
			return &GeneratedTools[i]
		}
	}
	return nil
}

// mustDecodeTools materializes the generated table. It panics on malformed
// input, which can only happen if the generated file is hand-edited.
func mustDecodeTools(raw string) []ToolDef {
	var tools []ToolDef
	if err := json.Unmarshal([]byte(raw), &tools); err != nil {
		panic("mcptools: generated table is malformed: " + err.Error())
	}
	return tools
}
